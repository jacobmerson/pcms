#!/usr/bin/env python3
"""splines-eqdsk: a tokamak equilibrium as a spline field.

A tokamak equilibrium is stored by the codes that compute it as an EQDSK file:
the poloidal magnetic flux psi(R, Z) on a uniform grid in the poloidal plane.
PCMS turns the flux into a field in a bicubic spline space, which, unlike the
linear (Lagrange) spaces, is smooth enough to differentiate: the gradient of
psi gives the poloidal magnetic field,

    B_R = -(1/R) dpsi/dZ,    B_Z = (1/R) dpsi/dR.

This is the Python twin of main.cpp. The file is generated by make_eqdsk.py
from an analytic Solov'ev equilibrium,

    psi(R, Z) = psi_axis + A (R^2 - R0^2)^2 + B Z^2,

so everything the example computes from the file is compared with the exact
answer.

  1. reading the file: the grid, and a field in a spline space on it;
  2. the gradient of the field, and the magnetic field from it;
  3. the magnetic axis, found as the zero of the gradient;
  4. a flux surface, sampled by bisection along rays from the axis;
  5. the checks: psi on the axis, B against the analytic field, B
     divergence-free on the surface.

Usage: main.py [path to an EQDSK file; default: the solovev.eqdsk next to it]
"""
import pathlib
import sys

import numpy as np
import pcms

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2] / "common"))
from example_utils import Report  # noqa: E402

# The equilibrium of make_eqdsk.py, for the comparisons.
R0 = 1.7
MINOR_RADIUS = 0.5
KAPPA = 1.6
PSI_AXIS = -0.4
PSI_BOUNDARY = 0.6
OUTER_SHIFT = (R0 + MINOR_RADIUS) ** 2 - R0 ** 2
COEFFICIENT_A = (PSI_BOUNDARY - PSI_AXIS) / OUTER_SHIFT ** 2
COEFFICIENT_B = (PSI_BOUNDARY - PSI_AXIS) / (KAPPA * MINOR_RADIUS) ** 2

# A bicubic spline reproduces the quartic psi to about h^4 times its fourth
# derivative / 77 (1e-6 here), and its gradient to one order less. The axis is
# at a node of the grid, where the spline is more accurate than elsewhere. The
# measured errors are printed.
AXIS_TOL = 1e-4
PSI_AXIS_TOL = 1e-7
FIELD_TOL = 1e-4
SURFACE_TOL = 1e-9
OUTBOARD_TOL = 1e-5
# B is divergence-free up to the symmetry of the mixed second derivatives of
# the spline, which a tensor-product spline of this psi has to rounding; the
# finite difference with a step of 1e-3 multiplies that by 1e3.
DIVERGENCE_TOL = 1e-8
STEP = 1e-3


def exact_b(r, z):
    """The poloidal field (B_R, B_Z) of the exact psi."""
    return (-2.0 * COEFFICIENT_B * z / r,
            4.0 * COEFFICIENT_A * (r ** 2 - R0 ** 2))


def read_eqdsk(path):
    """Reads the grid, psi, and psi on the axis and at the boundary from a
    G-EQDSK file: a header line whose last three integers are 0, nw and nh,
    then numbers in 16 characters, five to a line, with R varying fastest in
    psi. (The PCMS Python API has no EQDSK reader yet: the C++ example uses
    MakeEQDSKField.)"""
    with open(path) as f:
        header = f.readline()
        nw, nh = int(header[52:56]), int(header[56:60])
        first_psi = 20 + 4 * nw  # 20 numbers, then fpol, pres, ffprim, pprime
        numbers = []
        for line in f:
            line = line.rstrip("\n")
            numbers += [float(line[i:i + 16]) for i in range(0, len(line), 16)]
            if len(numbers) >= first_psi + nw * nh:
                break
    r_dim, z_dim, _, r_left, z_mid = numbers[0:5]
    psi_axis, psi_boundary = numbers[7], numbers[8]
    psi = np.array(numbers[first_psi:first_psi + nw * nh])
    return dict(nw=nw, nh=nh, r_min=r_left, r_dim=r_dim,
                z_min=z_mid - z_dim / 2.0, z_dim=z_dim, psi=psi,
                psi_axis=psi_axis, psi_boundary=psi_boundary)


class Flux:
    """Evaluates psi and its gradient at points of the (R, Z) plane."""

    def __init__(self, psi, system):
        self.psi = psi
        self.system = system
        self.query = pcms.QueryPoints(psi.get_space().get_geometry())
        # The gradient is a covector with physical components in the system of
        # the space: (dpsi/dR, dpsi/dZ). The view that an evaluation writes to
        # is tagged with the basis the caller expects, and PCMS refuses a
        # mismatch.
        self.gradient_basis = pcms.ValueBasis(
            system, pcms.ComponentScaling.Physical, pcms.values.Covector)

    def values(self, points):
        """psi at the points (rows of `points`: R, Z)."""
        self.query.locate(pcms.CoordinateView(self.system, points))
        out = np.zeros((len(points), 1))
        self.query.evaluate(self.psi, out)
        return out[:, 0]

    def gradient(self, points):
        """(dpsi/dR, dpsi/dZ) at the points."""
        self.query.locate(pcms.CoordinateView(self.system, points))
        out = np.zeros((len(points), 2))
        self.query.evaluate(self.psi,
                            pcms.ValueView(self.gradient_basis, out),
                            pcms.DifferentialOperator.Gradient)
        return out


def main():
    report = Report()
    # The file next to this script unless one is given on the command line.
    path = (sys.argv[1] if len(sys.argv) > 1
            else str(pathlib.Path(__file__).with_name("solovev.eqdsk")))

    # ---------------------------------------------------------------------
    # 1. Reading the file
    #
    # The file gives the grid and psi on it. The spline space is created on
    # a uniform grid in cylindrical (R, Z) coordinates, and psi is the values
    # of the DOF holders, which are the grid points, R varying fastest.
    eq = read_eqdsk(path)
    print("EQDSK: %d x %d points, R in [%.2f, %.2f], Z in [%.2f, %.2f]"
          % (eq["nw"], eq["nh"], eq["r_min"], eq["r_min"] + eq["r_dim"],
             eq["z_min"], eq["z_min"] + eq["z_dim"]))
    grid = pcms.UniformGrid2D()
    grid.bot_left = [eq["r_min"], eq["z_min"]]
    grid.edge_length = [eq["r_dim"], eq["z_dim"]]
    grid.divisions = [eq["nw"] - 1, eq["nh"] - 1]
    space = pcms.create_spline_space(pcms.create_uniform_grid_geometry(
        grid, pcms.csys.CylindricalRZ.create()))
    psi = space.create_function("psi")
    psi.set_dof_holder_data(eq["psi"].reshape(-1, 1))
    flux = Flux(psi, space.get_coordinate_system())
    psi_axis, psi_boundary = eq["psi_axis"], eq["psi_boundary"]

    # ---------------------------------------------------------------------
    # 2. The gradient, and the magnetic field
    #
    # The spline space supports the Gradient operator: evaluating with it
    # gives (dpsi/dR, dpsi/dZ) in place of psi. The poloidal field follows
    # from it. Compare it with the exact one on a 6 x 6 set of probes.
    probes = np.array([[1.45 + 0.06 * i, -0.5 + 0.2 * j]
                       for i in range(6) for j in range(6)])
    grad = flux.gradient(probes)
    b_r, b_z = exact_b(probes[:, 0], probes[:, 1])
    field_error = np.max(np.hypot(-grad[:, 1] / probes[:, 0] - b_r,
                                  grad[:, 0] / probes[:, 0] - b_z))
    print("poloidal field from the gradient: error %.3e" % field_error)

    # ---------------------------------------------------------------------
    # 3. The magnetic axis
    #
    # The axis is the minimum of psi, where its gradient vanishes. Newton's
    # method on the gradient, with the Jacobian (the Hessian of psi) by
    # central differences of the gradient, starts from the smallest value of
    # psi on the grid and converges in a few steps.
    best = np.argmin(eq["psi"])
    axis = np.array([[eq["r_min"] + eq["r_dim"] * (best % eq["nw"])
                      / (eq["nw"] - 1),
                      eq["z_min"] + eq["z_dim"] * (best // eq["nw"])
                      / (eq["nh"] - 1)]])
    residual = 0.0
    iterations = 0
    while iterations < 20:
        g = flux.gradient(axis)[0]
        residual = np.hypot(*g)
        if residual < 1e-12:
            break
        right = flux.gradient(axis + [STEP, 0.0])[0]
        left = flux.gradient(axis - [STEP, 0.0])[0]
        up = flux.gradient(axis + [0.0, STEP])[0]
        down = flux.gradient(axis - [0.0, STEP])[0]
        hessian = np.array([[right[0] - left[0], up[0] - down[0]],
                            [right[1] - left[1], up[1] - down[1]]]) \
            / (2.0 * STEP)
        axis = axis - np.linalg.solve(hessian, g)[None, :]
        iterations += 1
    psi_at_axis = flux.values(axis)[0]
    print("magnetic axis: R = %.6f, Z = %.6f after %d Newton steps "
          "(|grad psi| = %.1e), psi = %.8f"
          % (axis[0, 0], axis[0, 1], iterations, residual, psi_at_axis))

    # ---------------------------------------------------------------------
    # 4. A flux surface
    #
    # The surface halfway from the axis to the boundary in psi: for each of 64
    # directions, the point on the ray from the axis where psi crosses that
    # value, found by bisection. psi increases along every ray from the axis
    # and the rays end at the edge of the grid, where psi is larger, so the
    # bracket is known. All 64 bisections advance together, one evaluation of
    # 64 points per step.
    psi_target = psi_axis + 0.5 * (psi_boundary - psi_axis)
    num_rays = 64
    angle = 2.0 * np.pi * np.arange(num_rays) / num_rays
    direction = np.stack([np.cos(angle), np.sin(angle)], axis=1)
    bounds = ((eq["r_min"], eq["r_min"] + eq["r_dim"]),
              (eq["z_min"], eq["z_min"] + eq["z_dim"]))
    reach = np.full(num_rays, np.inf)
    for d in range(2):
        positive = direction[:, d] > 1e-12
        negative = direction[:, d] < -1e-12
        reach[positive] = np.minimum(
            reach[positive],
            (bounds[d][1] - axis[0, d]) / direction[positive, d])
        reach[negative] = np.minimum(
            reach[negative],
            (bounds[d][0] - axis[0, d]) / direction[negative, d])
    lo = np.zeros(num_rays)
    hi = (1.0 - 1e-9) * reach
    for _ in range(60):
        mid = 0.5 * (lo + hi)
        below = flux.values(axis + mid[:, None] * direction) < psi_target
        lo = np.where(below, mid, lo)
        hi = np.where(below, hi, mid)
    surface = axis + (0.5 * (lo + hi))[:, None] * direction
    surface_error = np.max(np.abs(flux.values(surface) - psi_target))
    print("flux surface psi = %.4f: R in [%.4f, %.4f], Z in [%.4f, %.4f]"
          % (psi_target, surface[:, 0].min(), surface[:, 0].max(),
             surface[:, 1].min(), surface[:, 1].max()))

    # The poloidal field divergence-free: div B = (1/R)(d(dpsi/dR)/dZ -
    # d(dpsi/dZ)/dR), by central differences of the gradient with a step of
    # 1e-3, at the points of the surface.
    right = flux.gradient(surface + [STEP, 0.0])
    left = flux.gradient(surface - [STEP, 0.0])
    up = flux.gradient(surface + [0.0, STEP])
    down = flux.gradient(surface - [0.0, STEP])
    r = surface[:, 0]
    divergence = np.max(np.abs((up[:, 0] - down[:, 0]) / (2.0 * STEP)
                               - (right[:, 1] - left[:, 1]) / (2.0 * STEP))
                        / r)
    b_max = np.max(np.hypot(*flux.gradient(surface).T) / r)
    print("max |B_pol| on the surface %.3f, max |div B| %.3e"
          % (b_max, divergence))

    # ---------------------------------------------------------------------
    # 5. The checks
    #
    # The axis of the Solov'ev equilibrium is at (R0, 0), and psi there is the
    # psi_axis of the file. The outboard point of the surface (the ray with
    # angle 0) has the exact radius R with (R^2 - R0^2)^2 = (psi - psi_axis) /
    # A.
    report.check_at_most("magnetic axis: R", abs(axis[0, 0] - R0), AXIS_TOL)
    report.check_at_most("magnetic axis: Z", abs(axis[0, 1]), AXIS_TOL)
    report.check_at_most("magnetic axis: psi is the file's psi_axis",
                         abs(psi_at_axis - psi_axis), PSI_AXIS_TOL)
    report.check_at_most("poloidal field from the gradient vs exact",
                         field_error, FIELD_TOL)
    report.check_at_most("flux surface: psi equals the target on all rays",
                         surface_error, SURFACE_TOL)
    r_outboard = np.sqrt(R0 ** 2
                         + np.sqrt((psi_target - PSI_AXIS) / COEFFICIENT_A))
    report.check_at_most("flux surface: outboard radius vs exact",
                         abs(surface[0, 0] - r_outboard), OUTBOARD_TOL)
    report.check_at_most("div B = 0 on the flux surface", divergence,
                         DIVERGENCE_TOL)
    return report.finish()


if __name__ == "__main__":
    sys.exit(main())
